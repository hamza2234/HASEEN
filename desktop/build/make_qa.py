    total = 0
    for section, items in SECTIONS:
        parts.append(f"<h2>{html.escape(section)}</h2>")
        for q, a in items:
            total += 1
            parts.append('<div class="qa">')
            parts.append(f'<div class="q">{html.escape(q)}</div>')
            parts.append(f'<div class="a">{html.escape(a)}</div>')
